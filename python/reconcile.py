"""
reconcile.py
============
Reconciles headline totals across:
  * Python   (python/metrics.py on the model CSVs)
  * SQL      (sql/08_validation_checks.sql on PostgreSQL)
  * DAX definitions (powerbi/dax_measures.md), re-implemented in pandas with DAX semantics.
    Power BI Desktop cannot run in this environment, so the DAX column verifies the
    *definitions*; check the same numbers in Power BI Desktop after building the report.

Also fails if any SQL assertion in 08_validation_checks.sql returns FAIL.
Writes reports/metrics/reconciliation.md.

Usage:  PGDATABASE=webanalytics python python/reconcile.py
"""
from __future__ import annotations

import os
import shutil
import subprocess
import sys
from pathlib import Path

import pandas as pd

sys.path.insert(0, str(Path(__file__).resolve().parent))
import metrics as m  # noqa: E402

ROOT = Path(__file__).resolve().parents[1]
MODEL = ROOT / "data" / "processed" / "model"


def python_totals():
    fs = pd.read_csv(MODEL / "fact_sessions.csv")
    ft = pd.read_csv(MODEL / "fact_transactions.csv")
    k = m.kpi_summary(fs, ft)
    py = {"total_sessions": k["total_sessions"], "total_visitors": k["total_visitors"],
          "engaged_sessions": k["engaged_sessions"], "purchasing_sessions": k["purchasing_sessions"],
          "total_transactions": k["total_transactions"], "total_revenue": k["total_revenue"],
          "net_revenue": k["net_revenue"], "funnel_purchase_stage": int(fs["reached_purchase"].sum())}
    dax = {  # DAX semantics, see powerbi/dax_measures.md
        "total_sessions": len(fs),                                                   # COUNTROWS(FactSessions)
        "total_visitors": fs["visitor_id"].nunique(),                                # DISTINCTCOUNT(visitor_id)
        "engaged_sessions": int(fs["engaged_session"].sum()),                        # SUM(engaged_session)
        "purchasing_sessions": ft["session_id"].nunique(),                           # DISTINCTCOUNT(FactTransactions[session_id])
        "total_transactions": ft["transaction_id"].nunique(),                        # DISTINCTCOUNT(transaction_id)
        "total_revenue": round(ft["revenue"].sum(), 2),                              # SUM(revenue)
        "net_revenue": round(ft.loc[ft.transaction_status == "completed", "revenue"].sum(), 2),  # CALCULATE(..., status="completed")
        "funnel_purchase_stage": int(fs["reached_purchase"].sum()),                  # SUM(reached_purchase)
    }
    return py, dax


def sql_results():
    if not shutil.which("psql"):
        return None, None, "psql not found"
    env = {**os.environ, "PGDATABASE": os.environ.get("PGDATABASE", "webanalytics")}
    r = subprocess.run(["psql", "-At", "-F", "|", "-v", "ON_ERROR_STOP=1", "-f", str(ROOT / "sql" / "08_validation_checks.sql")],
                       capture_output=True, text=True, env=env, cwd=ROOT)
    if r.returncode != 0:
        return None, None, r.stderr.strip()
    checks, totals = [], {}
    for line in r.stdout.strip().splitlines():
        parts = line.split("|")
        if len(parts) == 4:
            checks.append(dict(zip(["check_name", "expected", "actual", "status"], parts)))
        elif len(parts) == 2:
            v = float(parts[1])
            totals[parts[0]] = int(v) if v.is_integer() and "revenue" not in parts[0] else v
    return checks, totals, None


def main():
    py, dax = python_totals()
    checks, sql, err = sql_results()
    rows = []
    for k in py:
        s = sql.get(k) if sql else None
        ok = (abs(py[k] - dax[k]) < 0.005) and (s is None or abs(py[k] - s) < 0.005)
        rows.append({"metric": k, "python": py[k], "sql": s if s is not None else "not run",
                     "dax_definition": dax[k], "match": "PASS" if ok else "FAIL"})
    df = pd.DataFrame(rows)

    lines = ["# Reconciliation: Python vs SQL vs DAX definitions", "",
             "Generated by `python/reconcile.py`. The DAX column re-implements the documented DAX measure "
             "semantics in pandas (Power BI Desktop is not available in the build environment).", ""]
    lines += ["| Metric | Python | SQL | DAX definition | Status |", "|---|---:|---:|---:|---|"]
    for r in rows:
        sql_txt = r["sql"] if isinstance(r["sql"], str) else f"{r['sql']:,}"
        lines.append(f"| {r['metric']} | {r['python']:,} | {sql_txt} | {r['dax_definition']:,} | {r['match']} |")
    if checks is not None:
        n_fail = sum(c["status"] == "FAIL" for c in checks)
        lines += ["", f"## SQL assertions ({len(checks) - n_fail}/{len(checks)} passed)", "",
                  "| Check | Expected | Actual | Status |", "|---|---:|---:|---|"]
        lines += [f"| {c['check_name']} | {c['expected']} | {c['actual']} | {c['status']} |" for c in checks]
    else:
        lines += ["", f"SQL checks not run: {err}"]
    out = ROOT / "reports" / "metrics" / "reconciliation.md"
    out.write_text("\n".join(lines) + "\n")
    print(df.to_string(index=False))
    if checks is not None:
        print(f"SQL assertions: {sum(c['status'] == 'PASS' for c in checks)}/{len(checks)} PASS")
    else:
        print("SQL checks not run:", err)
    failed = (df["match"] == "FAIL").any() or (checks is not None and any(c["status"] == "FAIL" for c in checks))
    sys.exit(1 if failed else 0)


if __name__ == "__main__":
    main()
